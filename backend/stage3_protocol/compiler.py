"""Stage 3: protocol compiler. Owner B.

A FIXED template turns an ExperimentDesign into a program for the Opentrons Flex.
No LLM-generated code ever runs — only this template, parameterised by the validated
design. Gotchas baked in:
  * Flex deck slots use letter-number coordinates (e.g. D1), not OT-2 numbers.
  * A Flex protocol MUST declare a trash bin via load_trash_bin, or the simulator
    stops at the first tip drop.
  * API level 2.20 targets Opentrons 10.x (Flex).
"""

from __future__ import annotations

from pathlib import Path

from backend.contracts import ExperimentDesign

_PROTOCOLS_DIR = Path(__file__).resolve().parents[2] / "protocols"

# The fixed deck layout the template loads. Kept here so the simulator wrapper can report
# it as SimResult.deck even when the Opentrons package isn't installed. Mirrors the
# load_* calls in _TEMPLATE below.
DECK: list[dict] = [
    {"slot": "D1", "load_name": "opentrons_flex_96_tiprack_200ul",
     "display_name": "Flex 96 tip rack, 200 µL", "role": "tips", "contents": {}},
    {"slot": "D2", "load_name": "corning_96_wellplate_360ul_flat",
     "display_name": "Corning 96-well plate, 360 µL, flat", "role": "plate", "contents": {}},
    {"slot": "D3", "load_name": "nest_12_reservoir_15ml",
     "display_name": "NEST 12-well reservoir, 15 mL", "role": "reservoir",
     "contents": {"A1": "diluent", "A2": "compound"}},
    {"slot": "A3", "load_name": "trash_bin",
     "display_name": "Trash bin", "role": "trash", "contents": {}},
]

_TEMPLATE = '''"""AUTO-GENERATED by the fixed compiler template v2. Do not edit by hand.
Design: {design_id}  |  Target Opentrons Flex, API 2.20.

Layout: replicate r (0-based) uses plate row "ABCDEFGH"[r]; dilution point i uses
column i+1. Column 12 holds controls: {negative_wells} negative (diluent only) then
{positive_wells} positive (compound stock). Every dilution well ends at {diluent_uL} uL.
"""

metadata = {{"protocolName": "dose-response {design_id}", "author": "HackachusettsHealth"}}
requirements = {{"robotType": "Flex", "apiLevel": "2.20"}}


def run(protocol):
    trash = protocol.load_trash_bin("A3")  # REQUIRED on Flex or tip drop fails
    tipracks = [protocol.load_labware("{tiprack}", "D1")]
    if {second_rack}:
        tipracks.append(protocol.load_labware("{tiprack}", "C1"))
    plate = protocol.load_labware("{plate_labware}", "D2")
    reservoir = protocol.load_labware("nest_12_reservoir_15ml", "D3")
    pipette = protocol.load_instrument("{pipette}", "left", tip_racks=tipracks)

    diluent = reservoir["A1"]
    compound = reservoir["A2"]
    transfer_uL = {transfer_uL}
    diluent_uL = {diluent_uL}
    points = {points}
    replicates = {replicates}
    negative_wells = {negative_wells}
    positive_wells = {positive_wells}
    rows = "ABCDEFGH"

    # --- one replicate per plate row ---
    for r in range(replicates):
        row = plate.rows()[r]

        # 1. diluent into columns 2..points (one tip, no change)
        pipette.pick_up_tip()
        for col in range(1, points):
            pipette.transfer(diluent_uL, diluent, row[col], new_tip="never")
        pipette.drop_tip()

        # 2. seed column 1 with transfer_uL + diluent_uL of stock (new tip)
        pipette.transfer(transfer_uL + diluent_uL, compound, row[0])

        # 3. serial dilution col i -> i+1, mixing, new tip each step
        for col in range(points - 1):
            pipette.transfer(
                transfer_uL, row[col], row[col + 1], mix_after=(3, transfer_uL)
            )

        # 4. remove transfer_uL from the last column so it also ends at diluent_uL
        pipette.pick_up_tip()
        pipette.aspirate(transfer_uL, row[points - 1])
        pipette.drop_tip()

    # --- controls in column 12 (index 11) ---
    if negative_wells:
        pipette.pick_up_tip()
        for k in range(negative_wells):
            pipette.transfer(diluent_uL, diluent, plate.columns()[11][k], new_tip="never")
        pipette.drop_tip()
    if positive_wells:
        pipette.pick_up_tip()
        for k in range(positive_wells):
            well = plate.columns()[11][negative_wells + k]
            pipette.transfer(diluent_uL, compound, well, new_tip="never")
        pipette.drop_tip()
'''


def _tips_needed(design: ExperimentDesign) -> int:
    """R*(P+2) serial tips + 1 per non-empty control group (B1.1)."""
    r = design.replicates
    p = design.dilution.points
    tips = r * (p + 2)
    if design.controls.negative_wells:
        tips += 1
    if design.controls.positive_wells:
        tips += 1
    return tips


def cost_model(design: ExperimentDesign) -> dict:
    """Predicted cost of the v2 protocol, matching what the run log will count (B1.1).

    tips        = R*(P+2) + 1 per non-empty control group
    compound_uL = R*(transfer + diluent) + positive_wells*diluent
                  (each row seeds col 1 with transfer+diluent of stock; each positive
                   control well gets diluent of stock)
    plates      = 1
    """
    r = design.replicates
    t = design.volumes_uL.transfer
    d = design.volumes_uL.diluent
    compound_uL = r * (t + d) + design.controls.positive_wells * d
    return {"tips": _tips_needed(design), "compound_uL": float(compound_uL), "plates": 1}


def _render(design: ExperimentDesign) -> str:
    return _TEMPLATE.format(
        design_id=design.design_id,
        tiprack=design.tiprack,
        plate_labware=design.plate.labware,
        pipette=design.pipette,
        transfer_uL=design.volumes_uL.transfer,
        diluent_uL=design.volumes_uL.diluent,
        points=design.dilution.points,
        replicates=design.replicates,
        negative_wells=design.controls.negative_wells,
        positive_wells=design.controls.positive_wells,
        second_rack="True" if _tips_needed(design) > 96 else "False",
    )


def compile_design(design: ExperimentDesign) -> Path:
    """Render the template to protocols/<design_id>.py and return its path."""
    _PROTOCOLS_DIR.mkdir(parents=True, exist_ok=True)
    out = _PROTOCOLS_DIR / f"{design.design_id}.py"
    out.write_text(_render(design))
    return out


_WHATIF_DIR = _PROTOCOLS_DIR / "whatif"


def compile_whatif(design: ExperimentDesign) -> Path:
    """Compile a what-if design to protocols/whatif/<sha1>.py so it never overwrites a
    run's protocols/<design_id>.py. The filename hashes the design JSON (stable)."""
    import hashlib

    _WHATIF_DIR.mkdir(parents=True, exist_ok=True)
    digest = hashlib.sha1(design.model_dump_json().encode()).hexdigest()[:12]
    out = _WHATIF_DIR / f"{digest}.py"
    out.write_text(_render(design))
    return out
